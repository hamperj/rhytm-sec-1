/* Dumps PERF-1's 19 genres as RHYTM-SEC-1's styles, from PERF-1's own en_piece_g / en_piece_pats_g / en_piece_mods_g (run on
 * the build machine, writes perf/styles.h):
 *   STYLE_PAR   each genre's sound and feel, from its first piece (tempo, kits, lane levels, swing, bass ...)
 *   STYLE_MOD   its steps' tricks (accents, push, ratchets), from its first piece
 *   STYLE_PROB  for each drum lane and step, how often the genre's 60 patterns (10 pieces x 6) hit there, 0..255:
 *               what RHYTM-SEC-1's generator draws its patterns from
 *   cc -w -DEN_HOST -I../perf1/firmware/src/dsp -I../perf1/firmware/src dump.c -o dump -Wl,-undefined,dynamic_lookup */
#include <stdio.h>
#include "amb.c"

static const int KEEP[] = {P_TEMPO, P_ROOT, P_MODE, P_SWING, P_PULSE, P_BASS, P_DRIVE,
    P_KIT_KICK, P_KIT_SNARE, P_KIT_HAT, P_KIT_PERC,
    P_LANE + 0, P_LANE + 1, P_LANE + 2, P_LANE + 3, P_LANE + 4, P_LANE + 5, P_LANE + 6, P_LANE + 7, P_LANE + 8,
    P_LANE + 9, P_LANE + 10, P_LANE + 11, P_LANE + 12, P_LANE + 13, P_LANE + 14, P_LANE + 15, P_LANE + 16, P_LANE + 17,
    P_DENS, P_DENS1, P_DENS2, P_DENS3, P_DENS4, P_DENS5, P_PROB, P_PROB1, P_PROB2, P_PROB3, P_PROB4, P_PROB5,
    P_GHOST, P_ACCENT, P_HUMAN,
    P_BL_MODE, P_BL_LEN, P_BL_MOVE, P_BL_GLIDE, P_BASSOCT, P_OCT, P_DR_INST, P_DR_CUT, P_DR_RES,
    P_DE_TRIG, P_DE_ATK, P_DE_DEC, P_DE_AMT, P_TUNE};
#define NK ((int)(sizeof KEEP / sizeof KEEP[0]))

int main(void)
{
    int g, i, k, p, l, s;
    printf("/* generated by gen/dump.c from PERF-1 (deamonSLINKY/PERF-1 848b3c6): do not edit */\n");
    printf("#define PC_N %d\nstatic const int16_t STYLE_PAR[%d][PC_N] = {\n", NK, EN_NGENRE);
    for (g = 0; g < EN_NGENRE; g++) {
        int16_t par[P_NPARAMS];
        uint16_t pool;
        en_piece_g(g, 0, par, &pool);
        printf(" {");
        for (k = 0; k < NK; k++)
            printf("%d%s", par[KEEP[k]], k + 1 < NK ? "," : "");
        printf("}%s\n", g + 1 < EN_NGENRE ? "," : "");
    }
    printf("};\nstatic const uint8_t STYLE_MOD[%d][%d][16] = {\n", EN_NGENRE, EN_NLANE);
    for (g = 0; g < EN_NGENRE; g++) {
        uint8_t mod[EN_NLANE][16];
        en_piece_mods_g(g, 0, mod);
        printf(" {");
        for (l = 0; l < EN_NLANE; l++) {
            printf("{");
            for (s = 0; s < 16; s++)
                printf("%d%s", mod[l][s], s < 15 ? "," : "");
            printf("}%s", l + 1 < EN_NLANE ? "," : "");
        }
        printf("}%s\n", g + 1 < EN_NGENRE ? "," : "");
    }
    printf("};\nstatic const uint8_t STYLE_PROB[%d][%d][16] = {\n", EN_NGENRE, EN_NLANE);
    for (g = 0; g < EN_NGENRE; g++) {
        int n[EN_NLANE][16] = {{0}};
        for (i = 0; i < EN_NPIECES; i++) {
            uint16_t pats[EN_NPAT][EN_NLANE];
            en_piece_pats_g(g, i, pats);
            for (p = 0; p < EN_NPAT; p++)
                for (l = 0; l < EN_NLANE; l++)
                    for (s = 0; s < 16; s++)
                        n[l][s] += pats[p][l] >> s & 1u;
        }
        printf(" {");
        for (l = 0; l < EN_NLANE; l++) {
            printf("{");
            for (s = 0; s < 16; s++)
                printf("%d%s", (n[l][s] * 255 + EN_NPIECES * EN_NPAT / 2) / (EN_NPIECES * EN_NPAT), s < 15 ? "," : "");
            printf("}%s", l + 1 < EN_NLANE ? "," : "");
        }
        printf("}%s\n", g + 1 < EN_NGENRE ? "," : "");
    }
    printf("};\n");
    return 0;
}
